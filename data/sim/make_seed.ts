// Writes seed/buildings.json, seed/people.json, seed/fire_params.json, seed/staff.json and the generated
// spacetimedb/src/seed_data.ts (so reducers can seed / reset without an admin script).
//
//   node --experimental-strip-types data/sim/make_seed.ts
//
// Reads data/neighborhood.json + data/out/{building_risk,wind_replay,eaton_spread,risk_model,calibration}.json.
import { writeFileSync, mkdirSync } from 'node:fs';
import { assembleSeed, p_, staffRoster } from './seed_lib.ts';
import { ON_SITE_STAFF, PHONE_STAFF } from '../../spacetimedb/src/sim.ts';

const seed = assembleSeed();
mkdirSync(p_('seed'), { recursive: true });
const { buildings, people, params, meta } = seed;

writeFileSync(p_('seed/buildings.json'), JSON.stringify({ _note: 'SIMULATED neighbourhood. baseRisk from CAL FIRE DINS model (data/risk_model.py); fixes riskDrop from the model or the fire sim.', buildings }, null, 2) + '\n');
writeFileSync(p_('seed/people.json'), JSON.stringify({ _note: 'SIMULATED residents. Maria R. (1201) and Robert K. (1202, silent) are the demo residents.', people }, null, 2) + '\n');
// fuel on one line per row keeps the file readable.
const fp = JSON.stringify({ ...params, fuel: '__FUEL__' }, null, 2);
const fuelRows: string[] = [];
for (let y = 0; y < params.rows; y++) fuelRows.push('    ' + params.fuel.slice(y * params.cols, (y + 1) * params.cols).join(','));
writeFileSync(p_('seed/fire_params.json'), fp.replace('"__FUEL__"', '[\n' + fuelRows.join(',\n') + '\n  ]') + '\n');
writeFileSync(p_('seed/staff.json'), JSON.stringify(staffRoster(seed, ON_SITE_STAFF, PHONE_STAFF), null, 2) + '\n');

const ts = `// GENERATED by data/sim/make_seed.ts — do not edit. Re-run the data pipeline instead.
// SIMULATED neighbourhood; fire calibrated to the 2025 Eaton Fire; building risk from CAL FIRE DINS.
import type { Seed } from './sim';

export const SEED: Seed = ${JSON.stringify({ buildings, people, params })};
`;
writeFileSync(p_('spacetimedb/src/seed_data.ts'), ts);

const total = people.length;
console.log(`seed: ${buildings.length} buildings, ${total} people (${people.filter((x) => x.needsHelp).length} need help), ${buildings.reduce((s, b) => s + b.fixes.length, 0)} fixes`);
console.log(`Building 12 evacuation: ${meta.building12Evac}`);
for (const b of buildings) console.log(`  ${b.name.padEnd(15)} risk ${String(b.baseRisk).padStart(5)}  ref ETA ${b.referenceFireEtaMin ?? '(uncalibrated)'}  fixes: ${b.fixes.map((f) => `${f.name} −${f.riskDrop}`).join('; ')}`);
