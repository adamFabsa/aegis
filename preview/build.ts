// Builds preview/index.html: one self-contained page (opens from file://, no server, no npm install).
//   node --experimental-strip-types preview/build.ts
// Inlines the REAL engine (spacetimedb/src/sim.ts), the generated seed and the map geometry, so the preview
// always runs exactly the code the Spacetime module runs. Re-run after changing sim.ts or the seed.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p: string) => readFileSync(resolve(ROOT, p), 'utf8');

function exportsToLocals(code: string): { code: string; names: string[] } {
  const names: string[] = [];
  const out = code.replace(/^export\s+(function|const|class|let)\s+(\w+)/gm, (_m, kind: string, name: string) => {
    names.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*export\s/m.test(out)) throw new Error('unexpected export form left after stripping');
  if (/^\s*import\s/m.test(out)) throw new Error('unexpected import left after stripping');
  return { code: out, names };
}

const sim = exportsToLocals(stripTypeScriptTypes(read('spacetimedb/src/sim.ts')));
const seed = exportsToLocals(stripTypeScriptTypes(read('spacetimedb/src/seed_data.ts')));
const nb = JSON.parse(read('data/neighborhood.json'));
let app = read('preview/app.js');
app = app.replace(/^import .*$/gm, '');
app = app.replace(/^export\s+(function|const|class)\s/gm, '$1 ');
if (/^\s*(import|export)\s/m.test(app)) throw new Error('unexpected import/export left in app.js');

const bundle = [
  '// GENERATED by preview/build.ts — edit preview/app.js or spacetimedb/src/sim.ts, then rebuild.',
  `const S = (() => {\n${sim.code}\nreturn { ${sim.names.join(', ')} };\n})();`,
  `const { SEED } = (() => {\n${seed.code}\nreturn { ${seed.names.join(', ')} };\n})();`,
  `const NB = ${JSON.stringify(nb)};`,
  app,
].join('\n');

const page = read('preview/template.html').replace('/*__BUNDLE__*/', () => bundle.replace(/<\/script/gi, '<\\/script'));
writeFileSync(resolve(ROOT, 'preview/index.html'), page);
console.log(`preview/index.html: ${(page.length / 1024).toFixed(0)} KB, engine exports: ${sim.names.length}`);
